"""Backend: talks to Fusion BIP straight from this host over SOAP.

Queries run through a temporary data model: create -> run -> delete. The BI
Publisher session token is reused across calls, so the password is sent only at
the first login and again when the token expires.
"""

from __future__ import annotations

import hashlib
import re
import threading
import time
import uuid

from . import builders, soap
from .context import FusionContext
from .errors import FusionToolError, FusionUnreachable, SessionExpired

# (base_url, username) -> session token. Held in memory only, never written out.
_tokens: dict[tuple[str, str], str] = {}
# One lock per (base_url, username), so a slow login to one account does not hold up
# calls to the others.
_locks: dict[tuple[str, str], threading.Lock] = {}
_locks_guard = threading.Lock()
# (base_url, username) -> (time of a failed login, its message, a hash of the
# rejected password). While set, no new login is attempted with that same password,
# so an agent retrying in a loop cannot lock the account; a changed password is tried.
_failed: dict[tuple[str, str], tuple[float, str, str]] = {}
_BACKOFF_SECONDS = 300
_GENERATED = re.compile(r"<!--Generated by .*?-->\s*", re.S)


def _token(ctx: FusionContext, fresh: bool = False) -> tuple[str, str, str]:
    """Return (base_url, user, token), logging in only when there is no live token."""
    url, user, pw = ctx.fusion_login()
    key = (url, user.lower())
    pw_hash = hashlib.sha256(pw.encode("utf-8")).hexdigest()
    with _locks_guard:
        lock = _locks.setdefault(key, threading.Lock())
    with lock:
        if fresh or key not in _tokens:
            failed = _failed.get(key)
            if failed and failed[2] == pw_hash and time.time() - failed[0] < _BACKOFF_SECONDS:
                raise FusionToolError(
                    f"Login for {user} at {url} was rejected ({failed[1]}). Not retrying with the "
                    f"same password for {_BACKOFF_SECONDS // 60} minutes to avoid locking the "
                    "account. Update the password where it is set (fusion-mcp setup --instance "
                    "NAME --user NAME, your credential helper, or FUSION_PASSWORD); the next call "
                    "uses the new one.")
            try:
                _tokens[key] = soap.login(url, user, pw)
            except FusionUnreachable:
                raise  # says nothing about the password, so no back-off
            except FusionToolError as e:
                # Any rejected login backs off, whatever Fusion's wording, so a retry loop
                # cannot lock the account.
                _failed[key] = (time.time(), str(e), pw_hash)
                raise
            _failed.pop(key, None)
        return url, user, _tokens[key]


def query_fusion(ctx: FusionContext, sql: str) -> str:
    """Run one SELECT through a temporary data model, then delete the model.

    If the session token has expired, log in again once and carry on. The model is
    deleted with whichever token is current, so an expired session cannot leave it behind.
    """
    xdm = builders.build_data_model_xml(sql)
    url, user, token = _token(ctx)
    folder = f"/~{user}"
    name = "MCPQ_" + uuid.uuid4().hex[:10]
    path = f"{folder}/{name}.xdm"
    created = False
    try:
        for attempt in (1, 2):
            try:
                if not created:
                    soap.create_object(url, token, folder, name, "xdm", xdm)
                    created = True
                out = soap.decode_report_bytes(soap.run_data_model_in_session(url, token, path))
                # Drop BI Publisher's "Generated by ..." comment; it only names the temporary model.
                return _GENERATED.sub("", out, count=1)
            except SessionExpired:
                if attempt == 2:
                    raise
                url, user, token = _token(ctx, fresh=True)
    finally:
        if created:
            try:
                soap.delete_object(url, token, path)
            except FusionToolError:
                pass  # best-effort cleanup; the query result is already in hand
