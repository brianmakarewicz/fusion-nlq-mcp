"""The temporary data model must be deleted, even when the session expires mid-query."""

import pytest

from fusion_mcp import direct_client, soap
from fusion_mcp.context import FusionContext
from fusion_mcp.errors import FusionToolError, SessionExpired


@pytest.fixture
def fusion(monkeypatch):
    calls = []
    tokens = iter(["tok1", "tok2", "tok3"])
    monkeypatch.setattr(direct_client, "_token",
                        lambda ctx, fresh=False: ("https://pod", "fin_user", next(tokens)))
    monkeypatch.setattr(soap, "create_object",
                        lambda url, tok, folder, name, ext, xml: calls.append(("create", tok)))
    monkeypatch.setattr(soap, "delete_object",
                        lambda url, tok, path: calls.append(("delete", tok)))
    monkeypatch.setattr(soap, "decode_report_bytes", lambda raw: raw)
    return calls


def test_model_is_deleted_after_a_query(fusion, monkeypatch):
    monkeypatch.setattr(soap, "run_data_model_in_session",
                        lambda url, tok, path: "<!--Generated by x-->\n<ROWSET/>")
    assert direct_client.query_fusion(FusionContext(), "SELECT 1 FROM dual") == "<ROWSET/>"
    assert fusion == [("create", "tok1"), ("delete", "tok1")]


def test_model_is_deleted_with_the_new_token_after_the_session_expires(fusion, monkeypatch):
    def run(url, tok, path):
        if tok == "tok1":
            raise SessionExpired("invalid BIPSessionToken")
        return "<ROWSET/>"
    monkeypatch.setattr(soap, "run_data_model_in_session", run)
    assert direct_client.query_fusion(FusionContext(), "SELECT 1 FROM dual") == "<ROWSET/>"
    # Created once, run again with the fresh token, and deleted with the fresh token.
    assert fusion == [("create", "tok1"), ("delete", "tok2")]


def test_model_is_deleted_when_the_query_fails(fusion, monkeypatch):
    def run(url, tok, path):
        raise FusionToolError("ORA-00942: table or view does not exist")
    monkeypatch.setattr(soap, "run_data_model_in_session", run)
    with pytest.raises(FusionToolError, match="ORA-00942"):
        direct_client.query_fusion(FusionContext(), "SELECT 1 FROM nope")
    assert fusion == [("create", "tok1"), ("delete", "tok1")]


def test_nothing_is_deleted_when_create_fails(fusion, monkeypatch):
    def create(*args):
        raise FusionToolError("folder not found")
    monkeypatch.setattr(soap, "create_object", create)
    with pytest.raises(FusionToolError):
        direct_client.query_fusion(FusionContext(), "SELECT 1 FROM dual")
    assert fusion == []


def test_a_bad_query_never_reaches_fusion(fusion):
    with pytest.raises(FusionToolError, match="semicolon"):
        direct_client.query_fusion(FusionContext(), "SELECT 1 FROM dual; DELETE FROM x")
    assert fusion == []
